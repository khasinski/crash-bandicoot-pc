#!/usr/bin/env python3
"""Generate the PS1 RAM layout of the game's data from the decompilation.

The native game keeps its data in a host block that mirrors PS1 RAM. Every
data symbol of the original executable is a label at its original offset in
that block, so C code declares globals with ordinary `extern` declarations.
The startup code fills the block from SCUS_949.00 on the user's disc.

Input is the linked ELF of crash-bandicoot-decomp (`make build`, optionally
relinked with --emit-relocs); only symbol names and addresses are read.

    tools/scripts/gen_ram_layout.py path/to/main.elf
"""
import argparse
import re
from pathlib import Path

from elftools.elf.elffile import ELFFile

RAM_BASE = 0x80000000
RAM_SIZE = 0x800000           # 2 MiB of PS1 RAM plus room for the host stack
SCRATCH_BASE = 0x1F800000
SCRATCH_SIZE = 0x400
TEXT = (0x8001177C, 0x800514DC)

ROOT = Path(__file__).resolve().parents[2]


def collect(elf_path):
    elf = ELFFile(open(elf_path, "rb"))
    data, funcs = {}, {}
    for sym in elf.get_section_by_name(".symtab").iter_symbols():
        name, addr = sym.name, sym["st_value"]
        if not name or "." in name or name.startswith(("main_", "__", "_gp")):
            continue
        if not re.match(r"^[A-Za-z_]\w*$", name):
            continue
        kind = sym["st_info"]["type"]
        if kind == "STT_FUNC":
            funcs[name] = addr
            continue
        in_ram = RAM_BASE + 0x10000 <= addr < RAM_BASE + 0x200000
        in_scratch = SCRATCH_BASE <= addr < SCRATCH_BASE + SCRATCH_SIZE
        if not (in_ram or in_scratch):
            continue
        # Text labels are code, except words the hand-written code kept there.
        if TEXT[0] <= addr < TEXT[1] and kind != "STT_OBJECT":
            continue
        data.setdefault(name, addr)
    return data, funcs


def emit_block(lines, label, base, size, symbols):
    lines.append(f"    .globl S({label})")
    lines.append("    .p2align 12")
    lines.append(f"S({label}):")
    pos = base
    for addr, names in sorted(symbols.items()):
        if addr > pos:
            lines.append(f"    .space 0x{addr - pos:X}")
            pos = addr
        for name in sorted(names):
            lines.append(f"    .globl S({name})")
            lines.append(f"S({name}):")
    lines.append(f"    .space 0x{base + size - pos:X}")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("elf")
    parser.add_argument("--output", default=str(ROOT / "src/main/ram_layout.S"))
    parser.add_argument("--code-output", default=str(ROOT / "src/main/ram_code.inc"))
    args = parser.parse_args()

    data, funcs = collect(args.elf)
    ram, scratch = {}, {}
    for name, addr in data.items():
        (scratch if addr < RAM_BASE else ram).setdefault(addr, []).append(name)

    lines = [
        "/* Generated by tools/scripts/gen_ram_layout.py from the decompilation's",
        " * symbol table. Labels mark each data symbol at its PS1 RAM offset; the",
        " * contents come from SCUS_949.00 at startup. Do not edit. */",
        "#if defined(__APPLE__)",
        "#define S(x) _##x",
        "#else",
        "#define S(x) x",
        "#endif",
        "",
        "    .bss",
    ]
    emit_block(lines, "g_ps1_ram", RAM_BASE, RAM_SIZE, ram)
    lines.append("")
    emit_block(lines, "g_ps1_scratch", SCRATCH_BASE, SCRATCH_SIZE, scratch)
    lines.append("")
    lines.append("#if defined(__linux__) && defined(__ELF__)")
    lines.append('    .section .note.GNU-stack,"",%progbits')
    lines.append("#endif")
    Path(args.output).write_text("\n".join(lines) + "\n")
    print(f"{len(data)} data symbols -> {args.output}")

    # Code addresses stored in game memory map to the native functions that
    # the game sources define.
    defined = set()
    for src in (ROOT / "src/main").rglob("*.c"):
        text = re.sub(r"/\*.*?\*/", "", src.read_text(), flags=re.S)
        defined.update(re.findall(r"^(?!static)[A-Za-z_][\w \*]*?\b(\w+)\s*\([^;{}]*\)\s*\{", text, re.M))
    code = sorted((addr, name) for name, addr in funcs.items() if name in defined)
    out = ["/* Generated by tools/scripts/gen_ram_layout.py: PS1 address of each game",
           " * function defined in C. Sorted by address. Do not edit. */"]
    out += [f"RAM_CODE(0x{addr:08X}u, {name})" for addr, name in code]
    Path(args.code_output).write_text("\n".join(out) + "\n")
    print(f"{len(code)} functions -> {args.code_output}")


if __name__ == "__main__":
    main()
